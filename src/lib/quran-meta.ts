export function createInitialJuzMap(): Record<string, JuzReservation> {
  const map: Record<string, JuzReservation> = {};
  for (let i = 1; i <= 30; i++) {
    map[String(i)] = {
      number: i,
      status: 'available',
      holderName: null,
      hideName: false,
      holderUid: null,
      reservedAt: null,
      completedAt: null,
    };
  }
  return map;
}
